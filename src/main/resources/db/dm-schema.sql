-- ============================================================
-- AgentChat v2 用户管理 · 达梦数据库（DBTXZNT 模式）表结构
--
-- 执行方式：应用启动时 DmSchemaInitializer 按分号拆分逐条执行；
--           "对象已存在"类错误会自动跳过（幂等），其它错误只记录日志不阻断启动。
-- 手工执行：disql DBTXZNT/SYSDBAsysdba23@127.0.0.1:5236
--
-- 约定：
--   1. 主键由 Java 生成（usr_/rol_/grt_/prf_/log_ + 16 位十六进制），不使用序列/自增；
--   2. 时间统一用 BIGINT 存 epoch 毫秒，避免 DM 时间类型/时区/默认值方言差异；
--   3. DM 的 VARCHAR 默认按字节计长，中文字段按 UTF-8 三倍字节预留（如姓名 256）。
-- ============================================================

-- 用户
CREATE TABLE AUTH_USER (
  USER_ID VARCHAR(64) NOT NULL,
  LOGIN_NAME VARCHAR(128) NOT NULL,
  PASSWORD_HASH VARCHAR(512),
  DISPLAY_NAME VARCHAR(256),
  EMAIL VARCHAR(256),
  PHONE_NO VARCHAR(64),
  USER_SOURCE VARCHAR(32) DEFAULT 'local' NOT NULL,
  EXTERNAL_ID VARCHAR(256),
  ENABLED INT DEFAULT 1 NOT NULL,
  CREATED_AT BIGINT NOT NULL,
  UPDATED_AT BIGINT NOT NULL,
  LAST_LOGIN_AT BIGINT,
  CONSTRAINT PK_AUTH_USER PRIMARY KEY (USER_ID)
);

CREATE UNIQUE INDEX IDX_AUTH_USER_LOGIN ON AUTH_USER (LOGIN_NAME);

CREATE INDEX IDX_AUTH_USER_EXT ON AUTH_USER (USER_SOURCE, EXTERNAL_ID);

-- 角色
CREATE TABLE AUTH_ROLE (
  ROLE_ID VARCHAR(64) NOT NULL,
  ROLE_CODE VARCHAR(128) NOT NULL,
  ROLE_NAME VARCHAR(256) NOT NULL,
  ROLE_DESC VARCHAR(1000),
  BUILT_IN INT DEFAULT 0 NOT NULL,
  CREATED_AT BIGINT NOT NULL,
  UPDATED_AT BIGINT NOT NULL,
  CONSTRAINT PK_AUTH_ROLE PRIMARY KEY (ROLE_ID)
);

CREATE UNIQUE INDEX IDX_AUTH_ROLE_CODE ON AUTH_ROLE (ROLE_CODE);

-- 用户-角色
CREATE TABLE AUTH_USER_ROLE (
  USER_ID VARCHAR(64) NOT NULL,
  ROLE_ID VARCHAR(64) NOT NULL,
  CREATED_AT BIGINT NOT NULL,
  CONSTRAINT PK_AUTH_USER_ROLE PRIMARY KEY (USER_ID, ROLE_ID)
);

CREATE INDEX IDX_AUTH_USER_ROLE_ROLE ON AUTH_USER_ROLE (ROLE_ID);

-- 知识域授权：SUBJECT_TYPE=role|user，同一主体+域唯一
CREATE TABLE AUTH_KB_GRANT (
  GRANT_ID VARCHAR(64) NOT NULL,
  SUBJECT_TYPE VARCHAR(16) NOT NULL,
  SUBJECT_ID VARCHAR(64) NOT NULL,
  DOMAIN_KEY VARCHAR(256) NOT NULL,
  ACCESS_LEVEL VARCHAR(16) DEFAULT 'read' NOT NULL,
  CREATED_AT BIGINT NOT NULL,
  CONSTRAINT PK_AUTH_KB_GRANT PRIMARY KEY (GRANT_ID)
);

CREATE UNIQUE INDEX IDX_AUTH_KB_GRANT_ON ON AUTH_KB_GRANT (SUBJECT_TYPE, SUBJECT_ID, DOMAIN_KEY);

-- 用户画像：键值对（计数/偏好/主题词/显式记忆镜像）
CREATE TABLE USR_PROFILE (
  PROFILE_ID VARCHAR(64) NOT NULL,
  USER_ID VARCHAR(64) NOT NULL,
  PROFILE_KEY VARCHAR(256) NOT NULL,
  PROFILE_VALUE VARCHAR(2000),
  SOURCE_TYPE VARCHAR(32) DEFAULT 'auto' NOT NULL,
  UPDATED_AT BIGINT NOT NULL,
  CONSTRAINT PK_USR_PROFILE PRIMARY KEY (PROFILE_ID)
);

CREATE UNIQUE INDEX IDX_USR_PROFILE_KEY ON USR_PROFILE (USER_ID, PROFILE_KEY);

-- 审计日志
CREATE TABLE AUTH_AUDIT (
  LOG_ID VARCHAR(64) NOT NULL,
  USER_ID VARCHAR(64),
  ACTION_NAME VARCHAR(64) NOT NULL,
  TARGET_ID VARCHAR(128),
  DETAIL VARCHAR(2000),
  CLIENT_IP VARCHAR(64),
  CREATED_AT BIGINT NOT NULL,
  CONSTRAINT PK_AUTH_AUDIT PRIMARY KEY (LOG_ID)
);

CREATE INDEX IDX_AUTH_AUDIT_TIME ON AUTH_AUDIT (CREATED_AT);
